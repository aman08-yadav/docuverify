import { Router } from 'express';
import multer from 'multer';
import { config } from '../config/env.js';
import { requireAuth, requireAdmin } from '../middleware/auth.js';
import { uploadDocument, listDocuments, getDocument, streamDocument, reprocessDocument, updateFields, deleteDocAsync, consistency } from '../controllers/documentController.js';
import { reviewDocument } from '../controllers/adminController.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import { validateBody } from '../middleware/validate.js';
import { fieldCorrectionsSchema, adminReviewSchema } from '../validators/schemas.js';
const router = Router();
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: config.maxUploadBytes, files: 1, fields: 4, parts: 6 } });
router.use(requireAuth);
router.get('/consistency', asyncHandler(consistency));
router.get('/', asyncHandler(listDocuments));
router.post('/', upload.single('file'), asyncHandler(uploadDocument));
router.get('/:id/file', asyncHandler(streamDocument));
router.post('/:id/reprocess', asyncHandler(reprocessDocument));
router.patch('/:id/fields', validateBody(fieldCorrectionsSchema), asyncHandler(updateFields));
router.post('/:id/admin-review', requireAdmin, validateBody(adminReviewSchema), asyncHandler(reviewDocument));
router.get('/:id', asyncHandler(getDocument));
router.delete('/:id', asyncHandler(deleteDocAsync));
export default router;
